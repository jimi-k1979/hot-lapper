GLYPHS: Final[Mapping[str, tuple[str, ...]]] = {
    " ": ("." * GLYPH_WIDTH,) * GLYPH_HEIGHT,
    **{
        char: tuple(rows)
        for char, *rows in (line.split() for line in _GLYPHS.strip().splitlines())
    },
}


def text_width(string: str, scale: int = 1) -> int:
    return (len(string) * ADVANCE - 1) * scale


def glyph_rects(string: str, x: int, y: int, scale: int = 1) -> Iterator[Rect]:
    for index, char in enumerate(string):
        left = x + index * ADVANCE * scale
        for row, bits in enumerate(GLYPHS[char]):
            for column, bit in enumerate(bits):
                if bit == "#":
                    yield (left + column * scale, y + row * scale, scale, scale)
